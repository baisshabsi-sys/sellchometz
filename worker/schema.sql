CREATE TABLE IF NOT EXISTS submissions(id TEXT PRIMARY KEY, email_norm TEXT NOT NULL, last_norm TEXT NOT NULL, year INTEGER NOT NULL, ts INTEGER NOT NULL, data TEXT NOT NULL, imported INTEGER DEFAULT 0);
CREATE INDEX IF NOT EXISTS ix_sub_lookup ON submissions(email_norm,last_norm,ts);
CREATE TABLE IF NOT EXISTS settings(k TEXT PRIMARY KEY, v TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS attempts(ip TEXT NOT NULL, kind TEXT NOT NULL, ts INTEGER NOT NULL);
CREATE INDEX IF NOT EXISTS ix_att ON attempts(ip,kind,ts);
